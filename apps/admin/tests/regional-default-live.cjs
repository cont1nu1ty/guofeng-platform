// Creates one clearly labelled private draft using the regional account's default region.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('fs');
const env = fs.readFileSync(process.env.DEPLOY_ENV_FILE || 'deploy/.env', 'utf8');
const password = env.split('\n').find(line => line.startsWith('JIAFENG_DEV_PASSWORD=')).split('=').slice(1).join('=');
const base = process.env.ADMIN_LIVE_URL || 'http://127.0.0.1:18080/admin/';
const output = process.env.ADMIN_TEST_OUTPUT || '/tmp/jiafeng-admin-regional-live';
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/opt/google/chrome/chrome', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + '#/content');
  await page.getByPlaceholder('运营账号').fill('region_zj');
  await page.getByPlaceholder('账号密码').fill(password);
  await page.getByRole('button', { name: '登录工作空间' }).click();
  await page.getByRole('heading', { name: '内容与资讯', exact: true }).waitFor();
  await page.getByRole('button', { name: '新建内容', exact: true }).click();
  const dialog = page.getByRole('dialog');
  const region = await dialog.locator('.el-form-item').filter({ hasText: '发布范围' }).innerText();
  if (!region.includes('浙江省')) throw new Error('First-login content draft region is not authorized Zhejiang');
  const title = '联调验证-区域默认-' + Date.now();
  await dialog.getByPlaceholder('填写清晰、有辨识度的内容标题').fill(title);
  await dialog.locator('textarea').nth(0).fill('验证区域运营首次登录的默认发布地区。');
  await dialog.locator('textarea').nth(1).fill('这是开发联调草稿，用于确认区域运营无需重新选择省份即可保存授权区域的内容。');
  const responsePromise = page.waitForResponse(response => response.url().includes('/api/v1/admin/commands'));
  await dialog.getByRole('button', { name: /保存/ }).click();
  const response = await responsePromise;
  const body = await response.json();
  if (response.status() !== 200) throw new Error('Default region save failed: ' + response.status() + ' ' + body.code);
  const command = response.request().postDataJSON();
  if (command.data.region !== '浙江省') throw new Error('Saved request did not use authorized region');
  await dialog.waitFor({ state: 'hidden' });
  await page.getByText(title, { exact: true }).first().waitFor();
  await page.reload();
  await page.getByText(title, { exact: true }).first().waitFor();
  const report = { mode: 'Final Nginx build with real API, regional first-login draft', base, accountRole: 'regional_admin', title, initialRegion: '浙江省', savedRegion: command.data.region, saveStatus: response.status(), persistedAfterReload: true, errors };
  fs.writeFileSync(output + '/checks.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
  await browser.close();
  if (errors.length) process.exitCode = 1;
})().catch(error => { console.error(String(error).replaceAll(password, '[redacted]')); process.exit(1); });
