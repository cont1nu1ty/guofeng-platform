OUT=ROOT/'deploy/.local/non-ai-20261007'
def sql(statement):
    return subprocess.check_output(['docker','exec','-i',ENV['COMPOSE_PROJECT_NAME']+'-mysql-1','sh','-c','MYSQL_PWD="$MYSQL_PASSWORD" mysql -u jiafeng -D jiafeng -N -B'],input=statement.encode()).decode().strip()
def quote(value):return "'"+str(value).replace('\\','\\\\').replace("'","''")+"'"
def entity(admin,kind,id):return admin.call('GET','/admin/records/'+kind+'/'+id)[1]
def command(admin,name,id='',data=None,collection=None):
    body={'command':name,'entityId':id,'data':data or {}}
    if id:body['version']=entity(admin,collection,id)['lockVersion']
    return admin.call('POST','/admin/commands',body,{'Idempotency-Key':str(uuid.uuid4()),'X-Workspace-Mode':'compact'})[1]
def main():
    admin=Client('devadmin','admin');member=Client('member_zj');other=Client('member_bj')
    volume=command(admin,'saveCollection',data={'title':'导出快照验收 '+STAMP,'subtitle':'版本留存','theme':'传承','region':'zhejiang'})['result']['id']
    command(admin,'saveChapter',volume,{'title':'第一章','author':'验收作者','body':'原始正文 BEFORE '+STAMP},'collections')
    before=entity(admin,'collections',volume)
    jid=post(admin,'/admin/exports',{'kind':'collection','ids':[volume],'format':'docx','region':'zhejiang'})['id']
    command(admin,'saveChapter',volume,{'title':'第二章','author':'验收作者','body':'后来修改 AFTER '+STAMP},'collections')
    result=wait_job(admin,jid)
    blob=download(admin,'/admin/exports/'+jid+'/download','collection.docx')
    import io,zipfile
    with zipfile.ZipFile(io.BytesIO(blob)) as z:xml=z.read('word/document.xml').decode()
    check('collection export retains original snapshot after edits','BEFORE' in xml and 'AFTER' not in xml)
    other.call('GET','/admin/exports/'+jid+'/download',expected=403)
    admin.call('GET','/files/'+result['result']['fileId']+'/download',expected=404)
    check('generated document requires the authorizing business download endpoint')
    pdfid=post(admin,'/admin/exports',{'kind':'collection','ids':[volume],'format':'pdf','region':'zhejiang'})['id'];wait_job(admin,pdfid);download(admin,'/admin/exports/'+pdfid+'/download','collection.pdf')
    check('collection PDF and real Word file are generated by persistent executor')
    command(admin,'saveChapter',volume,{'title':'失败样例','author':'测试','body':'字体不支持的符号 🤯'},'collections')
    failedid=post(admin,'/admin/exports',{'kind':'collection','ids':[volume],'format':'pdf','region':'zhejiang'})['id']
    for _ in range(30):
        row=sql('SELECT status,attempts FROM jf_job WHERE id='+quote(failedid)+';').split('\t')
        if row[0]=='failed':break
        if row[0]=='queued' and int(row[1])>0:sql('UPDATE jf_job SET available_at=NOW(3) WHERE id='+quote(failedid)+" AND status='queued';")
        time.sleep(1)
    assert row[0]=='failed',row
    code=sql('SELECT error_code FROM jf_job WHERE id='+quote(failedid)+';')
    check('failed export retries at most three times and records failure reason',row[1]=='3' and code=='FONT_GLYPH_MISSING')
    admin.call('POST','/admin/exports/'+failedid+'/retry')
    admin.call('POST','/admin/exports/'+failedid+'/cancel')
    check('manual retry and cancellation persist',sql('SELECT status FROM jf_job WHERE id='+quote(failedid)+';')=='cancelled')
    _,_,headers=member.call('GET','/me/draft');etag=headers.get('ETag') or headers.get('Etag')
    member.call('PUT','/me/draft',draft(title='调度云草稿 '+STAMP),{'If-Match':etag})
    member.call('PUT','/me/delivery-preferences',{'digest':'daily','draftNotice':True,'reports':[]})
    uid=member.user['id']
    sql('UPDATE jf_delivery_preference SET enabled_at=DATE_SUB(NOW(),INTERVAL 3 DAY) WHERE owner_id='+uid+'; UPDATE jf_draft SET updated_at=DATE_SUB(NOW(),INTERVAL 4 DAY) WHERE user_id='+uid+';')
    notification='schedule_fixture_'+STAMP
    payload=json.dumps({'title':'摘要源业务消息','content':'隔离验收数据','sourceType':'fixture'},ensure_ascii=False)
    sql('INSERT INTO jf_entity(id,kind,owner_id,region_id,status,payload,created_at) VALUES('+quote(notification)+",'notification',"+uid+",'zhejiang','unread',"+quote(payload)+',DATE_SUB(NOW(),INTERVAL 1 DAY));')
    admin.call('PUT','/me/delivery-preferences',{'digest':'off','draftNotice':True,'reports':['month','quarter','year']})
    sql('UPDATE jf_delivery_preference SET enabled_at=DATE_SUB(NOW(),INTERVAL 2 YEAR) WHERE owner_id='+admin.user['id']+';')
    version=sql('SELECT version FROM jf_draft WHERE user_id='+uid+';')
    today=dt.datetime.now(ZoneInfo('Asia/Shanghai')).date()
    draft_key='draft:'+uid+':'+version
    digest_key='digest:'+uid+':daily:'+str(today-dt.timedelta(days=1))
    month_end=today.replace(day=1);month_start=(month_end-dt.timedelta(days=1)).replace(day=1)
    quarter_end=today.replace(month=((today.month-1)//3)*3+1,day=1)
    quarter_start=(quarter_end-dt.timedelta(days=1)).replace(month=((quarter_end-dt.timedelta(days=1)).month-1)//3*3+1,day=1)
    period_keys=['month:'+str(month_start),'quarter:'+str(quarter_start),'year:'+str(today.replace(year=today.year-1,month=1,day=1))]
    periods_where=' WHERE owner_id='+admin.user['id']+' AND period_key IN ('+','.join(quote(k) for k in period_keys)+')'
    for _ in range(80):
        counts=sql('SELECT COUNT(DISTINCT kind) FROM jf_notification_delivery WHERE delivery_key IN ('+quote(draft_key)+','+quote(digest_key)+');')
        periods=sql('SELECT COUNT(*) FROM jf_report_period'+periods_where+';')
        if int(counts)==2 and int(periods)==3:break
        time.sleep(1)
    check('real scheduler sends draft and daily digest with persistent delivery ledger',int(counts)==2)
    check('scheduler archives one monthly quarterly yearly report job per owner period',int(periods)==3)
    for report_id in sql('SELECT job_id FROM jf_report_period'+periods_where+';').splitlines():wait_job(admin,report_id)
    due=sql('SELECT COUNT(*) FROM jf_notification_delivery WHERE delivery_key='+quote(draft_key)+';')
    check('one stale draft version creates one reminder',int(due)==1)
    # Do not leave recurring fixture preferences enabled in a retained test environment.
    member.call('PUT','/me/delivery-preferences',{'digest':'off','draftNotice':False,'reports':[]});admin.call('PUT','/me/delivery-preferences',{'digest':'off','draftNotice':False,'reports':[]})
    (OUT/'jobs-schedule.json').write_text(json.dumps({'passed':RESULTS,'volumeId':volume,'snapshotJobId':jid,'failedJobId':failedid},ensure_ascii=False,indent=2)+'\n')
if __name__=='__main__':main()
